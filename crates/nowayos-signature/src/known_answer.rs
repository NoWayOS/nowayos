//! One known answer from another implementation: a message, a public key
//! and the signature over the message, made once with OpenSSL 3.0.22 in
//! the dev image (2026-11-01), the private key deleted at once inside the
//! container, which was then removed. A check here, on the host and in a PD
//! (`systems/signature-test`), shows that a signature made outside
//! RustCrypto - as an HSM's will be - is accepted, and that a one-bit change
//! to any part is not. Its s is above half the group order, as OpenSSL's
//! signatures often are: it is accepted.
//!
//! Only public values: no private key is in this repository, or anywhere.
//! Made with, in a temporary folder inside the dev container:
//!
//! ```text
//! openssl ecparam -name prime256v1 -genkey -noout -out key.pem
//! openssl ec -in key.pem -pubout -conv_form uncompressed -outform DER -out pub.der
//! openssl dgst -sha256 -sign key.pem -out sig.der msg.bin
//! rm key.pem
//! ```
//!
//! [`PUBLIC_KEY`] is the last 65 bytes of `pub.der`, and [`SIGNATURE`] the
//! two integers of `sig.der`'s DER `SEQUENCE`, r then s, each as 32 bytes.
//! OpenSSL's own check of the three passed (`openssl dgst -sha256 -verify`).

